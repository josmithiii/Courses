#!/usr/bin/env python3
"""Generate a book course's exercise bank (<book>/exercises/*.md) from the book's JSON.

Each of JOS's online books that has a course here keeps its interactive-course data in
its own repo (the same exercises the online edition shows):

    <books dir>/<book>/course/data/exercises/<book>-exercises.json   # HTML-marked-up text
    <books dir>/<book>/course/data/outline.json                      # book order of pages
    <books dir>/<book>/course/data/page-metadata.json                # page -> chapter, title, prev

The plugin builder ships only Markdown, so the JSON is rendered to one Markdown file
per chapter, with HTML markup turned into plain Unicode text the tutor can read and
quote in chat. The output is committed; regenerate after a book's exercises change.

    tools/build_book_exercises.py                  # regenerate every book's exercises/
    tools/build_book_exercises.py sasp             # just one book
    tools/build_book_exercises.py --check          # exit 1 if any exercises/ is stale
    tools/build_book_exercises.py mdft --src DIR   # one book, explicit course/data dir

The books dir is $JOS_BOOKS_DIR, else /w.
"""

from __future__ import annotations

import argparse
import filecmp
import html
import json
import os
import re
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any, NoReturn

REPO = Path(__file__).resolve().parent.parent
BOOKS_DIR = Path(os.environ.get("JOS_BOOKS_DIR", "/w"))


@dataclass(frozen=True)
class Book:
    course: str  # course directory in this repo, and the book's id / URL path
    title: str

    @property
    def url(self) -> str:
        return f"https://ccrma.stanford.edu/~jos/{self.course}/"

    @property
    def default_src(self) -> Path:
        return BOOKS_DIR / self.course / "course/data"

    @property
    def out_dir(self) -> Path:
        return REPO / self.course / "exercises"

    def generated_note(self) -> str:
        return (
            f"<!-- Generated by tools/build_book_exercises.py from the {self.course} book's"
            f" course/data/exercises/{self.course}-exercises.json - do not edit here; edit the"
            " book and regenerate. -->"
        )


BOOKS: dict[str, Book] = {
    b.course: b
    for b in [
        Book("mdft", "Mathematics of the DFT"),
        Book("filters", "Introduction to Digital Filters with Audio Applications"),
        Book("sasp", "Spectral Audio Signal Processing"),
    ]
}

OVERLINE = "\u0305"  # combining overline: complex conjugate, as the books write it


def die(msg: str) -> NoReturn:
    print(f"*** build_book_exercises: {msg}", file=sys.stderr)
    sys.exit(1)


def load_json(path: Path) -> Any:
    if not path.is_file():
        die(f"missing source file {path} (set --src or $JOS_BOOKS_DIR)")
    return json.loads(path.read_text())


def _script(match: re.Match[str], mark: str) -> str:
    body = match.group(1)
    text = f"{mark}{body}" if re.fullmatch(r"\w+", body) else f"{mark}({body})"
    # A space keeps a following symbol out of the script: z_1 S_N, not z_1S_N.
    rest = match.string[match.end():]
    return text + " " if rest[:1].isalnum() else text


def _overline(match: re.Match[str]) -> str:
    # Bar the leading symbol only (X̅(k), s̅_k(n)), as the bank's other conjugates are written.
    body = html.unescape(match.group(1))
    return body[0] + OVERLINE + body[1:]


def html_to_text(s: str) -> str:
    """Turn the exercises' inline HTML into plain Unicode with CS-style scripts.

    <i> is dropped (it marks math variables), <b>/<strong>/<em>/<code> become Markdown,
    <sup>/<sub> become ^x / ^(...) and _x / _(...), the overline span becomes a
    combining overline, and entities are unescaped. Anything else that looks like
    a tag is left alone only if it is plain text such as "<x,y>"; an unknown real
    tag is an error.
    """
    s = re.sub(r"</?i>", "", s)
    s = re.sub(r'<span style="text-decoration: ?overline">(.*?)</span>', _overline, s)
    s = re.sub(r"</?u>", "", s)
    s = re.sub(r"<(b|strong)>(.*?)</\1>", r"**\2**", s)
    s = re.sub(r"<em>(.*?)</em>", r"*\1*", s)
    s = re.sub(r"<code>(.*?)</code>", r"`\1`", s)
    # Innermost-first, so nested scripts render inside-out.
    for _ in range(3):
        s = re.sub(r"<sup>((?:(?!<su[bp]>).)*?)</sup>", lambda m: _script(m, "^"), s)
        s = re.sub(r"<sub>((?:(?!<su[bp]>).)*?)</sub>", lambda m: _script(m, "_"), s)
    # Any remaining tag-shaped markup is unhandled HTML (math like "<x,y>" doesn't match).
    leftover = re.findall(r"</?[A-Za-z][A-Za-z0-9]*(?:\s[^>]*)?/?>", s)
    if leftover:
        die(f"unconverted HTML tag(s) {leftover} in: {s[:120]}")
    s = s.replace("&thinsp;", " ").replace("&nbsp;", " ")
    s = html.unescape(s)
    return re.sub(r"[ \t]+", " ", s).strip()


def slugify(title: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def page_order(
    outline: list[dict[str, Any]], meta: dict[str, Any], pages: set[str]
) -> tuple[dict[str, float], dict[str, str]]:
    """Book order of every exercise page, plus the outline page each unlisted page follows.

    Pages missing from the outline (untitled "Example:" subpages) are placed by
    walking their prev links back to the nearest outline page.
    """
    order: dict[str, float] = {e["file"]: float(i) for i, e in enumerate(outline)}
    anchor: dict[str, str] = {}
    for page in sorted(pages - order.keys()):
        prev = meta[page].get("prev")
        hops = 1
        while prev not in order or prev in anchor:
            if prev is None or hops > 20:
                die(f"cannot place page {page} in book order (no outline ancestor via prev links)")
            prev = meta[prev].get("prev")
            hops += 1
        anchor[page] = prev
        order[page] = order[prev] + hops / 100
    return order, anchor


def chapter_files(outline: list[dict[str, Any]]) -> dict[str, tuple[str, str]]:
    """Chapter title -> (chapter number, output file stem), e.g. ('2', 'ch02-complex-numbers').

    Unnumbered top-level parts (Preface, Summary and Conclusions) get number "" and a bare slug.
    """
    chapters: dict[str, tuple[str, str]] = {}
    for e in outline:
        if e["depth"] != 1:
            continue
        num = e["num"]
        title = html.unescape(e["title"])
        if not num:
            chapters[title] = ("", slugify(title))
            continue
        prefix = f"ch{int(num):02d}" if num.isdigit() else f"app{num}"
        chapters[title] = (num, f"{prefix}-{slugify(title)}")
    return chapters


def render_exercise(ex: dict[str, Any]) -> list[str]:
    concepts = ", ".join(ex["concepts"])
    lines = [f"#### `{ex['id']}` - difficulty {ex['difficulty']}; concepts: {concepts}", ""]
    lines.append(f"**Q.** {html_to_text(ex['question'])}")
    lines.append("")
    for opt in ex["options"]:
        lines.append(f"- ({opt['id']}) {html_to_text(opt['text'])}")
    lines.append("")
    for i, hint in enumerate(ex["hints"], 1):
        lines.append(f"Hint {i}: {html_to_text(hint)}")
        lines.append("")
    if ex["correct"] not in {o["id"] for o in ex["options"]}:
        die(f"exercise {ex['id']}: correct answer {ex['correct']!r} is not an option")
    lines.append(f"**Answer: ({ex['correct']}).** {html_to_text(ex['explanation'])}")
    lines.append("")
    return lines


def build(book: Book, src: Path, out: Path) -> int:
    exercises = load_json(src / f"exercises/{book.course}-exercises.json")["exercises"]
    outline = load_json(src / "outline.json")
    meta = load_json(src / "page-metadata.json")

    ids = [e["id"] for e in exercises]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        die(f"duplicate exercise ids: {dupes}")
    for e in exercises:
        if e["type"] != "multiple-choice":
            die(f"exercise {e['id']}: unsupported type {e['type']!r}")
        if e["page"] not in meta:
            die(f"exercise {e['id']}: page {e['page']} not in page-metadata.json")

    chapters = chapter_files(outline)
    order, anchor = page_order(outline, meta, {e["page"] for e in exercises})
    by_chapter: dict[str, list[dict[str, Any]]] = {}
    for e in sorted(exercises, key=lambda e: order[e["page"]]):  # stable: keeps bank order within a page
        chapter = html.unescape(meta[e["page"]]["chapter"])
        if chapter not in chapters:
            die(f"exercise {e['id']}: chapter {chapter!r} is not a top-level part in outline.json")
        by_chapter.setdefault(chapter, []).append(e)

    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    index = [
        book.generated_note(),
        "",
        f"# {book.course.upper()} exercise bank - index",
        "",
        f"{len(exercises)} multiple-choice exercises from the interactive online edition of",
        f"*{book.title}* ({book.url}), one file per chapter, in book order.",
        "Each exercise names the book page it belongs to, its difficulty (1-3), and concept",
        "tags. Answers and explanations are included: they are for the tutor, never to be",
        "shown before the learner has committed to an answer.",
        "",
        "| Chapter | File | Exercises |",
        "|---|---|---|",
    ]
    ordered = [t for t in (html.unescape(e["title"]) for e in outline if e["depth"] == 1) if t in by_chapter]
    for title in ordered:
        num, stem = chapters[title]
        exs = by_chapter[title]
        label = f"{num} {title}".strip()
        index.append(f"| {label} | [`{stem}.md`]({stem}.md) | {len(exs)} |")
        lines = [book.generated_note(), "", f"# Exercises - {label}", ""]
        current_page = None
        for e in exs:
            if e["page"] != current_page:
                current_page = e["page"]
                pm = meta[current_page]
                number = pm.get("sectionNumber", "")
                page_title = html.unescape(pm["title"]).rstrip(":")
                if current_page in anchor:
                    page_title += f" (follows {html.unescape(meta[anchor[current_page]]['title'])})"
                lines += [f"## {number} {page_title}".replace("##  ", "## "), "",
                          f"Book page: {book.url}{current_page}", ""]
            lines += render_exercise(e)
        (out / f"{stem}.md").write_text("\n".join(lines))
    index.append("")
    (out / "index.md").write_text("\n".join(index))
    return len(exercises)


def stale_files(a: Path, b: Path) -> list[str]:
    files_a = {p.relative_to(a) for p in a.rglob("*") if p.is_file()} if a.exists() else set()
    files_b = {p.relative_to(b) for p in b.rglob("*") if p.is_file()}
    changed = [str(r) for r in files_a & files_b if not filecmp.cmp(a / r, b / r, shallow=False)]
    return sorted([str(r) for r in files_a ^ files_b] + changed)


def check(book: Book, src: Path) -> list[str]:
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "exercises"
        build(book, src, fresh)
        return stale_files(book.out_dir, fresh)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("books", nargs="*", help=f"books to build (default: all of {', '.join(BOOKS)})")
    ap.add_argument("--src", type=Path, help="the book's course/data directory (one book only)")
    ap.add_argument("--check", action="store_true", help="exit 1 if any <book>/exercises/ is stale")
    args = ap.parse_args()
    unknown = [b for b in args.books if b not in BOOKS]
    if unknown:
        die(f"unknown book(s) {unknown}; known: {', '.join(BOOKS)}")
    books = [BOOKS[b] for b in (args.books or BOOKS)]
    if args.src and len(books) != 1:
        die("--src needs exactly one book")
    stale_books: list[str] = []
    for book in books:
        src = args.src or book.default_src
        rel = book.out_dir.relative_to(REPO)
        if args.check:
            stale = check(book, src)
            if stale:
                stale_books.append(f"{rel}/ ({', '.join(stale)})")
            else:
                print(f"{rel}/ is up to date")
        else:
            n = build(book, src, book.out_dir)
            print(f"wrote {n} exercises to {rel}/")
    if stale_books:
        die(f"stale: {'; '.join(stale_books)}; run tools/build_book_exercises.py")


if __name__ == "__main__":
    main()
