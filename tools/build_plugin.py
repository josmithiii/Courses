#!/usr/bin/env python3
"""Build the `courses` Claude plugin from the course directories.

Each course becomes one Skill in courses-plugin/skills/<course>/. The repo's
course directories stay the single source of truth; courses-plugin/ is a
generated build output (committed, so the plugin installs straight from GitHub
via the root .claude-plugin/marketplace.json).

    tools/build_plugin.py room-acoustics      # build the plugin with these courses
    tools/build_plugin.py --all               # build it with every course
    tools/build_plugin.py --check             # exit 1 if courses-plugin/ is stale

The one real transformation: the "Content vs. learner state" section of each
course's lesson.md and CLAUDE.md is replaced by a plugin version. In the plugin
the content is the skill's own folder (read-only, replaced on every plugin
update), and the learner-state location must work in both Claude Code and the
Claude desktop app's Cowork mode, where only the folder the learner selected
survives the session.

Shared curriculum assets are bundled too: every `../curricula/assets/<dir>/<file>`
a course names is copied into the skill as `assets/<dir>/<file>` (with that
directory's README.md and SOURCE.md, for provenance and license), and the
references are rewritten to match. A plugin install has no repo beside it, so
this is the only way a lesson can reach its through-line clip, note or corpus.
"""

from __future__ import annotations

import argparse
import filecmp
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path
from typing import NoReturn

REPO = Path(__file__).resolve().parent.parent
PLUGIN_DIR_NAME = "courses-plugin"
PLUGIN_NAME = "courses"
PLUGIN_DISPLAY_NAME = "JOS Courses"  # what the desktop app lists and searches; the bare name drowns among connectors
PLUGIN_VERSION = "0.5.1"
TEMPLATE_COURSE = "course-template"

ASSET_PREFIX = "../curricula/assets/"
ASSET_REF = re.compile(re.escape(ASSET_PREFIX) + r"([A-Za-z0-9_-]+)/([A-Za-z0-9_.-]*)")
ASSET_ALWAYS = ("README.md", "SOURCE.md")  # provenance and license travel with any asset

LESSON_STATE_HEADING = "## Content vs. learner state (important)"
CONTEXT_STATE_HEADING = "## Content vs. learner state (architecture)"

GENERATED_NOTE = (
    "<!-- Generated by tools/build_plugin.py from the {course}/ course directory"
    " - do not edit here; edit the course and rebuild. -->"
)


def die(msg: str) -> NoReturn:
    print(f"*** build_plugin: {msg}", file=sys.stderr)
    sys.exit(1)


def all_courses() -> list[str]:
    return sorted(
        d.name
        for d in REPO.iterdir()
        if (d / ".claude/commands/lesson.md").is_file() and d.name != TEMPLATE_COURSE
    )


def split_frontmatter(text: str, where: Path) -> tuple[dict[str, str], str]:
    """Minimal `key: value` frontmatter parser (the lesson.md files use only `description`)."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        die(f"{where}: expected YAML frontmatter starting with '---'")
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        die(f"{where}: unterminated frontmatter")
    meta: dict[str, str] = {}
    for line in lines[1:end]:
        if ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip()] = value.strip().strip("\"'")
    return meta, "\n".join(lines[end + 1 :]).lstrip("\n")


def replace_section(text: str, heading: str, replacement: str, where: Path) -> str:
    """Replace the `## ` section titled `heading` (up to the next `## ` heading)."""
    lines = text.split("\n")
    starts = [i for i, line in enumerate(lines) if line.rstrip() == heading]
    if len(starts) != 1:
        die(f"{where}: expected exactly one '{heading}' section, found {len(starts)}")
    start = starts[0]
    end = next(
        (i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines)
    )
    return "\n".join(lines[:start] + replacement.rstrip("\n").split("\n") + [""] + lines[end:])


def lesson_state_section(course: str) -> str:
    return f"""{LESSON_STATE_HEADING}
This course separates shipped **content** from personal **learner state**:

- **Content (read-only, never write here):** this skill's folder - `syllabus.md`,
  `progress.template.md`, `CLAUDE.md`, and any other course files beside this
  `SKILL.md`. The plugin system replaces this folder on every update, so anything
  written into it is lost.
- **Learner state (read AND write here):** a *data root* the learner owns. Resolve
  it in this order, and tell the learner which one you are using:
  1. If the environment variable `COURSES_DATA_DIR` is set, use it.
  2. Else if a folder `Courses-data/` exists in the workspace folder (the folder
     this session was started in; in Cowork, the folder the learner selected), use it.
  3. Else if `$HOME/Documents/Courses-data/` exists, use it.
  4. Else this is a first run. Do **not** choose silently: ask the learner where to
     keep their progress, recommending
     - in Claude Code (a terminal, or the desktop app's Code tab):
       `~/Documents/Courses-data`;
     - in the desktop app's Cowork mode: `Courses-data/` inside the folder they
       selected for this task - only that folder survives the session, so never
       use `$HOME` or a temporary directory there.

  If the chosen location cannot be written, stop and say so plainly - never fall
  back to a temporary location, or the learner's progress silently disappears.

  This course's state lives in `<data root>/{course}/`:
  - `<data root>/{course}/progress.md` - durable progress tracker
  - `<data root>/{course}/lessons/YYYY-MM-DD.md` - per-day logs
"""


CONTEXT_STATE_SECTION = f"""{CONTEXT_STATE_HEADING}
Shipped course **content** is this skill's folder and is read-only at runtime.
Personal **learner state** (`progress.md` and `lessons/YYYY-MM-DD.md`) lives in the
learner's data root, resolved as described in `SKILL.md` under "Content vs.
learner state". Never write personal progress into this folder.
"""


def skill_md(course: str) -> str:
    lesson_path = REPO / course / ".claude/commands/lesson.md"
    meta, body = split_frontmatter(lesson_path.read_text(), lesson_path)
    if "description" not in meta:
        die(f"{lesson_path}: frontmatter has no 'description'")
    description = (
        f"{meta['description'].rstrip('.')}. Use when the learner wants to start,"
        f" continue, or resume the {course} course - e.g. \"let's do today's"
        f" {course} lesson\"."
    )
    body = replace_section(body, LESSON_STATE_HEADING, lesson_state_section(course), lesson_path)
    preamble = f"""## Course files - read these first
This skill's folder (the directory containing this `SKILL.md`) **is** the course
directory: wherever the instructions below say "the repo", "the course
directory", or "the course dir", they mean this folder. Before anything else,
read `CLAUDE.md` in this folder - it is the course's tutor guidance and is not
loaded automatically here. Shared curriculum assets the course uses (audio clips,
notes, corpora) are bundled under `assets/` in this folder.
"""
    return (
        "---\n"
        f"name: {course}\n"
        f"description: {json.dumps(description, ensure_ascii=False)}\n"
        "---\n\n"
        f"{GENERATED_NOTE.format(course=course)}\n\n"
        f"{preamble}\n{localize_assets(body)}"
    )


def course_texts(course: str) -> list[Path]:
    """Every Markdown file the course ships, lesson.md included."""
    src = REPO / course
    lesson = src / ".claude/commands/lesson.md"
    return [lesson] + sorted(
        p for p in src.rglob("*.md")
        if not any(part.startswith(".") for part in p.relative_to(src).parts)
    )


def bundled_assets(course: str) -> list[Path]:
    """Asset files (relative to curricula/assets/) the course references, plus each
    referenced directory's README.md and SOURCE.md. A named file that is missing fails."""
    root = REPO / "curricula/assets"
    wanted: set[Path] = set()
    for path in course_texts(course):
        for d, name in ASSET_REF.findall(path.read_text()):
            if not (root / d).is_dir():
                die(f"{path}: references missing asset directory {ASSET_PREFIX}{d}/")
            if name:
                if not (root / d / name).is_file():
                    die(f"{path}: references missing asset {ASSET_PREFIX}{d}/{name}")
                wanted.add(Path(d) / name)
            wanted |= {Path(d) / a for a in ASSET_ALWAYS if (root / d / a).is_file()}
    return sorted(wanted)


def bundle_assets(course: str, dest: Path) -> None:
    for rel in bundled_assets(course):
        out = dest / "assets" / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(REPO / "curricula/assets" / rel, out)


def localize_assets(text: str) -> str:
    """Point repo-layout asset paths at the copies bundled in the skill."""
    return text.replace(ASSET_PREFIX, "assets/")


def copy_course_content(course: str, dest: Path) -> None:
    """Copy the course's shipped content, Markdown and SVG figures (hidden dirs like .claude/ excluded)."""
    src = REPO / course
    for path in sorted(src.rglob("*")):
        rel = path.relative_to(src)
        if any(part.startswith(".") for part in rel.parts) or path.is_dir():
            continue
        if path.suffix not in (".md", ".svg"):
            die(f"{path}: unsupported course file type - teach build_plugin.py how to ship it")
        out = dest / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        if path.suffix == ".svg":
            shutil.copyfile(path, out)
            continue
        text = path.read_text()
        if rel == Path("CLAUDE.md"):
            text = replace_section(text, CONTEXT_STATE_HEADING, CONTEXT_STATE_SECTION, path)
        elif rel == Path("SKILL.md"):
            die(f"{path}: a course file named SKILL.md would collide with the generated skill")
        out.write_text(localize_assets(text))


def plugin_json() -> str:
    manifest = {
        "name": PLUGIN_NAME,
        "displayName": PLUGIN_DISPLAY_NAME,
        "description": (
            "Self-paced, tutor-style courses: Claude teaches one concept at a time,"
            " checks understanding with small exercises, and keeps your progress in a"
            " folder you own."
        ),
        "version": PLUGIN_VERSION,
        "author": {"name": "Julius O. Smith III", "url": "https://ccrma.stanford.edu/~jos/"},
        "homepage": "https://github.com/josmithiii/Courses",
        "repository": "https://github.com/josmithiii/Courses",
        "keywords": ["courses", "tutor", "learning", "education"],
    }
    return json.dumps(manifest, indent=2) + "\n"


def readme_md(courses: list[str]) -> str:
    rows = "\n".join(f"| `{c}` | \"let's do today's {c} lesson\" |" for c in courses)
    return f"""# courses - a Claude plugin

Self-paced, tutor-style courses run by Claude. Each course is a Skill: Claude acts
as a patient tutor, teaches one concept at a time, checks understanding with a
small exercise before moving on, and keeps your progress and per-day lesson logs
in a folder **you** own.

**Generated** from the course directories of
[josmithiii/Courses](https://github.com/josmithiii/Courses) by
`tools/build_plugin.py` - edit the courses there, not these files. In the Claude
desktop app it is listed (and searchable) as **{PLUGIN_DISPLAY_NAME}**.

## Install

**Recommended - one line in a terminal** (needs Claude Code installed). It covers
both Claude Code and the Claude desktop app's Code tab, which share one setup:

```bash
claude plugin marketplace add https://github.com/josmithiii/Courses && claude plugin install {PLUGIN_NAME}@josmithiii-courses
```

Then start a session in any folder (a terminal, or the desktop app's Code tab) and
name a course. Always use the full URL: the desktop app stores that form, and Claude
Code refuses the same marketplace under a second form.

**Point-and-click (unreliable as of Oct 2026):** the desktop app's Code tab ->
Customize -> Plugins -> + Add -> Add marketplace accepts the URL, but in testing the
plugin ("{PLUGIN_DISPLAY_NAME}") never appeared under Discover, even after Check for
updates. If it isn't listed, run the one-liner - it then shows up in the app at once.

## Courses

| Course | To start, say |
|---|---|
{rows}

## Your progress

Each course keeps `progress.md` (what you've mastered, what's next) and
`lessons/YYYY-MM-DD.md` (a record of each session) under a data root, chosen in
this order: `$COURSES_DATA_DIR`; `Courses-data/` in your workspace folder;
`~/Documents/Courses-data/`. On your first lesson Claude asks where to put it.
Nothing is ever written into the plugin itself.
"""


def build(courses: list[str], out: Path) -> None:
    known = set(all_courses())
    for course in courses:
        if course not in known:
            die(f"no such course: '{course}' (have: {', '.join(sorted(known))})")
    (out / ".claude-plugin").mkdir(parents=True)
    (out / ".claude-plugin/plugin.json").write_text(plugin_json())
    (out / "README.md").write_text(readme_md(courses))
    for course in courses:
        dest = out / "skills" / course
        copy_course_content(course, dest)
        bundle_assets(course, dest)
        (dest / "SKILL.md").write_text(skill_md(course))


def built_courses(plugin_dir: Path) -> list[str]:
    skills = plugin_dir / "skills"
    if not skills.is_dir():
        die(f"{plugin_dir}: no skills/ directory - nothing to check")
    return sorted(d.name for d in skills.iterdir() if d.is_dir())


def diff_trees(a: Path, b: Path) -> list[str]:
    """Relative paths that differ between two trees (missing, extra, or changed)."""
    files_a = {p.relative_to(a) for p in a.rglob("*") if p.is_file()}
    files_b = {p.relative_to(b) for p in b.rglob("*") if p.is_file()}
    changed = [
        str(rel) for rel in files_a & files_b if not filecmp.cmp(a / rel, b / rel, shallow=False)
    ]
    return sorted([str(r) for r in files_a ^ files_b] + changed)


def is_generated_plugin(path: Path) -> bool:
    manifest = path / ".claude-plugin/plugin.json"
    return manifest.is_file() and json.loads(manifest.read_text()).get("name") == PLUGIN_NAME


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("courses", nargs="*", help="course directories to include")
    parser.add_argument("--all", action="store_true", help="include every course")
    parser.add_argument("--check", action="store_true", help="fail if the plugin is stale")
    parser.add_argument("--out", type=Path, default=REPO / PLUGIN_DIR_NAME, help="output dir")
    args = parser.parse_args()

    if args.check:
        if args.courses or args.all:
            die("--check rebuilds the courses already in the plugin; give no course list")
        with tempfile.TemporaryDirectory() as tmp:
            fresh = Path(tmp) / PLUGIN_DIR_NAME
            build(built_courses(args.out), fresh)
            stale = diff_trees(args.out, fresh)
        if stale:
            die(f"{args.out} is stale - rerun tools/build_plugin.py. Differs: {', '.join(stale)}")
        print(f"{args.out}: up to date")
        return

    courses = all_courses() if args.all else args.courses
    if not courses:
        die("give course names or --all")
    if args.out.exists():
        if not is_generated_plugin(args.out):
            die(f"{args.out} exists and is not a generated '{PLUGIN_NAME}' plugin - refusing to replace it")
        shutil.rmtree(args.out)
    build(courses, args.out)
    print(f"Built {args.out} with {len(courses)} course(s): {', '.join(courses)}")


if __name__ == "__main__":
    main()
